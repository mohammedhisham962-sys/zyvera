-- CyberShield Portal Supabase PostgreSQL Database Schema

-- ==========================================
-- 1. Profiles Table (Links to auth.users)
-- ==========================================
CREATE TABLE IF NOT EXISTS public.profiles (
    id UUID PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
    username TEXT UNIQUE NOT NULL,
    email TEXT NOT NULL,
    role TEXT NOT NULL DEFAULT 'student' CHECK (role IN ('student', 'faculty', 'admin')),
    status TEXT NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE', 'BANNED')),
    created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL
);

ALTER TABLE public.profiles ENABLE ROW LEVEL SECURITY;

-- Drop policies if they exist to avoid duplication errors on re-run
DROP POLICY IF EXISTS "Allow public read-only access to profiles" ON public.profiles;
DROP POLICY IF EXISTS "Allow users to update their own profile" ON public.profiles;
DROP POLICY IF EXISTS "Allow admins to manage all profiles" ON public.profiles;
DROP POLICY IF EXISTS "Allow public insert to profiles" ON public.profiles;

-- Create Policies
CREATE POLICY "Allow public read-only access to profiles" 
ON public.profiles FOR SELECT 
TO authenticated, anon
USING (true);

CREATE POLICY "Allow users to update their own profile" 
ON public.profiles FOR UPDATE 
TO authenticated 
USING (id = auth.uid())
WITH CHECK (id = auth.uid());

CREATE POLICY "Allow admins to manage all profiles" 
ON public.profiles FOR ALL 
TO authenticated 
USING (
    coalesce(auth.jwt() -> 'user_metadata' ->> 'role', '') = 'admin'
);

CREATE POLICY "Allow public insert to profiles" 
ON public.profiles FOR INSERT 
TO anon, authenticated
WITH CHECK (true);


