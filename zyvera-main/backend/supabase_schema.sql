-- ==========================================
-- 7. Incidents Table
-- ==========================================
CREATE TABLE IF NOT EXISTS public.incidents (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title TEXT NOT NULL,
    category TEXT NOT NULL,
    description TEXT NOT NULL,
    reporter TEXT REFERENCES public.profiles(username) ON DELETE CASCADE ON UPDATE CASCADE,
    status TEXT NOT NULL DEFAULT 'Pending' CHECK (status IN ('Pending', 'Resolved')),
    solution TEXT DEFAULT '' NOT NULL,
    timestamp TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL,
    image_data TEXT,
    voice_data TEXT
);

ALTER TABLE public.incidents ENABLE ROW LEVEL SECURITY;

-- Drop policies if they exist
DROP POLICY IF EXISTS "Allow users to read their reported incidents" ON public.incidents;
DROP POLICY IF EXISTS "Allow users to report incidents" ON public.incidents;
DROP POLICY IF EXISTS "Allow admins to resolve incidents" ON public.incidents;

-- Create Policies
CREATE POLICY "Allow users to read their reported incidents" 
ON public.incidents FOR SELECT 
TO authenticated 
USING (
    reporter = coalesce(auth.jwt() -> 'user_metadata' ->> 'username', '') OR
    coalesce(auth.jwt() -> 'user_metadata' ->> 'role', '') = 'admin'
);

CREATE POLICY "Allow users to report incidents" 
ON public.incidents FOR INSERT 
TO authenticated 
WITH CHECK (
    reporter = coalesce(auth.jwt() -> 'user_metadata' ->> 'username', '')
);

CREATE POLICY "Allow admins to resolve incidents" 
ON public.incidents FOR UPDATE 
TO authenticated 
USING (
    coalesce(auth.jwt() -> 'user_metadata' ->> 'role', '') = 'admin'
);


